static void expect_decode(const char* encoded, int encoded_bytes, int width, int height) {
    int actual_width = 0;
    int actual_height = 0;
    void* pixels = NULL;
    unsigned long long pixel_bytes = 0ULL;
    int status = std_macos_encoded_image_decode(encoded, encoded_bytes, 1024, 4, 4, 16LL, &actual_width, &actual_height, &pixels, &pixel_bytes);
    if (status != BTRC_ENCODED_IMAGE_DECODE_OK) { fprintf(stderr, "decode failed for %02x%02x (%d bytes) with status %d\n", (unsigned int)(unsigned char)encoded[0], (unsigned int)(unsigned char)encoded[1], encoded_bytes, status); }
    assert(status == BTRC_ENCODED_IMAGE_DECODE_OK);
    assert(actual_width == width && actual_height == height && pixels != NULL && pixel_bytes == (unsigned long long)width * (unsigned long long)height * 4ULL);
    std_macos_encoded_image_release(pixels);
}

int main(void) {
    for (int iteration = 0; iteration < 128; iteration++) {
        expect_decode(PNG, (int)sizeof(PNG) - 1, 2, 2);
        expect_decode(JPEG, (int)sizeof(JPEG) - 1, 2, 2);
        expect_decode(GIF, (int)sizeof(GIF) - 1, 1, 1);
    }
    int width = 0;
    int height = 0;
    void* pixels = NULL;
    unsigned long long pixel_bytes = 0ULL;
    assert(std_macos_encoded_image_decode(PNG, (int)sizeof(PNG) - 1, 1024, 4, 4, 16LL, &width, &height, &pixels, &pixel_bytes) == BTRC_ENCODED_IMAGE_DECODE_OK);
    const unsigned char* rgba = (const unsigned char*)pixels;
    if (rgba[0] != 255U || rgba[1] != 0U || rgba[2] != 0U || rgba[3] != 255U) { for (size_t index = 0U; index < 16U; index++) { fprintf(stderr, "%u%c", (unsigned int)rgba[index], index == 15U ? '\n' : ' '); } }
    assert(rgba[0] == 255U && rgba[1] == 0U && rgba[2] == 0U && rgba[3] == 255U);
    assert(rgba[4] == 0U && rgba[5] == 255U && rgba[6] == 0U && rgba[7] == 128U);
    assert(rgba[11] == 0U);
    assert(rgba[12] == 255U && rgba[13] == 255U && rgba[14] == 255U && rgba[15] == 64U);
    std_macos_encoded_image_release(pixels);
    assert(std_macos_encoded_image_decode(PNG, (int)sizeof(PNG) - 1, 1024, 1, 2, 2LL, &width, &height, &pixels, &pixel_bytes) == BTRC_ENCODED_IMAGE_DECODE_LIMIT_EXCEEDED);
    assert(pixels == NULL && pixel_bytes == 0ULL);
    assert(std_macos_encoded_image_decode(PNG, 24, 1024, 4, 4, 16LL, &width, &height, &pixels, &pixel_bytes) == BTRC_ENCODED_IMAGE_DECODE_CORRUPT);
    assert(std_macos_encoded_image_decode("not an image", 12, 1024, 4, 4, 16LL, &width, &height, &pixels, &pixel_bytes) == BTRC_ENCODED_IMAGE_DECODE_UNSUPPORTED);
    puts("PASS MacOsEncodedImageDecoderSmoke");
    return 0;
}
