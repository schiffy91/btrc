"""Generate the Wayland client's numeric keyboard registry and Unicode case properties."""

import argparse
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

PROTO_SHA256 = "4ba0724695c817a08b4ea3a79c5e8a52e0798cc8d5906281b10f89dc6225208d"
UNICODE_SHA256 = "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c"
DEFINITION = re.compile(r"^#define XK_(\w+)[ \t]+(0x[0-9a-fA-F]+)[ \t]*(?:/\*(.*?)\*/)?[ \t]*$", re.M)
UNICODE = re.compile(r"\bU\+([0-9A-Fa-f]{4,6})\b")
OUTPUT = ROOT / "src/stdlib/GUI/Linux/Wayland"


def reviewed(path: Path, digest: str) -> str:
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != digest:
        raise ValueError(f"{path} differs from the reviewed upstream source")
    return data.decode()


def generate(definitions: Path, unicode_data: Path, output: Path) -> None:
    source = reviewed(definitions, PROTO_SHA256)
    ucd = reviewed(unicode_data, UNICODE_SHA256)
    notice = source.split("*/", 1)[0].split("\n", 1)[1].rstrip("*\n")
    (output / "KEYSYM-LICENSE.txt").write_text(notice + "\n")
    names = {}
    legacy = {}
    for name, value, comment in DEFINITION.findall(source):
        symbol = int(value, 16)
        names[name] = symbol
        scalar = UNICODE.search(comment)
        if 0x100 <= symbol < 0xFE00 and scalar:
            legacy[symbol] = int(scalar[1], 16)

    rows = [
        "/* xorgproto 2024.1 keysym registry. Copyright 1987, 1994, 1998 The Open Group and 1987 Digital Equipment Corporation.",
        " * See KEYSYM-LICENSE.txt. Generated by tools.ui.wayland_keysym_data. */",
        "static const struct { const char *name; uint32_t symbol; } keysymNames[] = {",
        *(f'    {{"{name}", 0x{symbol:x}}},' for name, symbol in sorted(names.items())),
        "};",
        "static const struct { uint32_t symbol, scalar; } legacyKeysyms[] = {",
        *(f"    {{0x{symbol:x}, 0x{scalar:x}}}," for symbol, scalar in sorted(legacy.items())),
        "};",
    ]
    (output / "KeysymData.h").write_text("\n".join(rows) + "\n")

    rows = [
        "/* Unicode 17.0.0 case categories and simple uppercase mappings. Copyright © Unicode, Inc.",
        " * See ../../Text/UNICODE-LICENSE.txt. Generated by tools.ui.wayland_keysym_data. */",
        "static const struct { uint32_t scalar, upper; uint8_t kind; } symbolCases[] = {",
    ]
    for line in ucd.splitlines():
        fields = line.split(";")
        # XKB types can pair different letters, e.g. long s and capital sharp s.
        kind = {"Ll": 1, "Lu": 2, "Lt": 2}.get(fields[2], 0)
        if kind or fields[12]:
            rows.append(f"    {{0x{int(fields[0], 16):x}, 0x{int(fields[12] or fields[0], 16):x}, {kind}}},")
    (output / "KeysymCaseData.h").write_text("\n".join([*rows, "};"]) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("keysymdef", type=Path, help="xorgproto 2024.1 include/X11/keysymdef.h")
    parser.add_argument("unicode_data", type=Path, help="Unicode 17.0.0 UnicodeData.txt")
    args = parser.parse_args()
    generate(args.keysymdef, args.unicode_data, OUTPUT)
