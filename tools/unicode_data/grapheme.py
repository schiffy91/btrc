"""Build grapheme-break, Indic conjunct and extended pictographic properties from Unicode 17.0.0."""

import argparse
from itertools import groupby
from pathlib import Path

from tools.unicode_data.properties import SOURCE, VERSION, interval, records

OUTPUT = Path(__file__).resolve().parents[2] / "src/stdlib/GUI/Text/GraphemeData.h"
BREAKS = (
    "Other",
    "CR",
    "LF",
    "Control",
    "Extend",
    "ZWJ",
    "Regional_Indicator",
    "Prepend",
    "SpacingMark",
    "L",
    "V",
    "T",
    "LV",
    "LVT",
)
INDIC = ("None", "Consonant", "Extend", "Linker")


def generate(root):
    props = bytearray(0x110000)
    source = root / "auxiliary/GraphemeBreakProperty.txt"
    assert f"GraphemeBreakProperty-{VERSION}.txt" in source.read_text().splitlines()[0]
    for span, prop in records(source):
        start, end = interval(span)
        props[start:end] = bytes([BREAKS.index(prop)]) * (end - start)
    # UAX #29 classifies precomposed Hangul syllables algorithmically.
    for cp in range(0xAC00, 0xD7A4):
        assert props[cp] == BREAKS.index("LV" if (cp - 0xAC00) % 28 == 0 else "LVT")
        props[cp] = 0
    for row in records(root / "DerivedCoreProperties.txt"):
        if row[1] == "InCB":
            start, end = interval(row[0])
            for cp in range(start, end):
                props[cp] |= INDIC.index(row[2]) << 4
    for span, prop in records(root / "emoji/emoji-data.txt"):
        if prop == "Extended_Pictographic":
            start, end = interval(span)
            for cp in range(start, end):
                props[cp] |= 64
    output = [
        f"/* Generated by tools/unicode_data/grapheme.py from Unicode {VERSION}.",
        f" * Source {SOURCE}. Normative property data only.",
        " * Copyright © 2025 Unicode, Inc. See UNICODE-LICENSE.txt. */",
        "static const struct { uint32_t first; uint8_t properties; } graphemeClasses[] = {",
    ]
    first = 0
    for properties, items in groupby(props):
        output.append(f"    {{0x{first:x}, 0x{properties:02x}}},")
        first += sum(1 for _ in items)
    return "\n".join([*output, "};", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ucd", type=Path)
    OUTPUT.write_text(generate(parser.parse_args().ucd))
