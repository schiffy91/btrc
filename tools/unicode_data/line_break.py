"""Generate compact line-break properties from the Unicode 17.0.0 Character Database."""

import argparse
from array import array
from itertools import groupby
from pathlib import Path

from tools.unicode_data.bidi import SOURCE, VERSION, interval, records

OUTPUT = Path(__file__).resolve().parents[2] / "src/stdlib/GUI/Text/LineBreakData.h"
CLASSES = [
    "AL",
    "AK",
    "AP",
    "AS",
    "B2",
    "BA",
    "BB",
    "BK",
    "CB",
    "CL",
    "CM",
    "CP",
    "CR",
    "EB",
    "EM",
    "EX",
    "GL",
    "H2",
    "H3",
    "HH",
    "HL",
    "HY",
    "ID",
    "IN",
    "IS",
    "JL",
    "JT",
    "JV",
    "LF",
    "NL",
    "NS",
    "NU",
    "OP",
    "PO",
    "PR",
    "QU",
    "RI",
    "SP",
    "SY",
    "VF",
    "VI",
    "WJ",
    "ZW",
    "ZWJ",
]


def generate(root):
    source = root / "LineBreak.txt"
    assert f"LineBreak-{VERSION}.txt" in source.read_text().splitlines()[0]
    general = bytearray(0x110000)
    for fields in records(root / "UnicodeData.txt"):
        cp = int(fields[0], 16)
        if fields[1].endswith(", First>"):
            first = cp
            continue
        first = first if fields[1].endswith(", Last>") else cp
        category = {"Mn": 2, "Mc": 2, "Pi": 3, "Pf": 4}.get(fields[2], 1)
        general[first : cp + 1] = bytes([category]) * (cp - first + 1)
    props = array("H", [0]) * 0x110000
    for span, name in records(source):
        start, end = interval(span)
        for cp in range(start, end):
            resolved = {"AI": "AL", "SG": "AL", "XX": "AL", "CJ": "NS"}.get(name, name)
            if name == "SA":
                resolved = "CM" if general[cp] == 2 else "AL"
            props[cp] = CLASSES.index(resolved)
    for span, width in records(root / "EastAsianWidth.txt"):
        if width in ("F", "W", "H"):
            start, end = interval(span)
            for cp in range(start, end):
                props[cp] |= 64
    for span, prop in records(root / "emoji/emoji-data.txt"):
        if prop == "Extended_Pictographic":
            start, end = interval(span)
            for cp in range(start, end):
                if not general[cp]:
                    props[cp] |= 512
    for cp, category in enumerate(general):
        if category == 3:
            props[cp] |= 128
        elif category == 4:
            props[cp] |= 256
    props[0x25CC] |= 1024
    # Remove algorithmically distributed Hangul syllables from the range table.
    for cp in range(0xAC00, 0xD7A4):
        assert props[cp] == CLASSES.index("H3" if (cp - 0xAC00) % 28 else "H2") | 64
        props[cp] = CLASSES.index("H2") | 64
    lines = [
        f"/* Generated by tools/unicode_data/line_break.py from Unicode {VERSION}.",
        f" * Source {SOURCE}. Normative property data only.",
        " * Copyright © 2025 Unicode, Inc. See UNICODE-LICENSE.txt. */",
        "enum Class { " + ", ".join(CLASSES) + ", END };",
        "static const struct { uint32_t first; uint16_t properties; } lineClasses[] = {",
    ]
    first = 0
    for value, group in groupby(props):
        lines.append(f"    {{0x{first:x}, {value}}},")
        first += sum(1 for _ in group)
    return "\n".join([*lines, "};", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ucd", type=Path)
    OUTPUT.write_text(generate(parser.parse_args().ucd))
